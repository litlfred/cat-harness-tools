import { describe, expect, it } from "bun:test";
import { parseArchimate } from "../schemas/archimate.ts";
import { actorTypeOf, actorsFsh, actorsOf, handWrittenActors } from "./archimate-actors.ts";

const XML = `<?xml version="1.0" encoding="UTF-8"?>
<archimate:model xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" xmlns:archimate="http://www.archimatetool.com/archimate" name="Tiny" id="id-model" version="5.0.0">
  <folder name="Application" id="id-f1" type="application">
    <element xsi:type="archimate:ApplicationComponent" name="Client Registry" id="id-cr">
      <documentation>Keeps one record per person, "uniquely".</documentation>
      <property key="fhir-actor" value="ClientRegistry"/>
    </element>
    <element xsi:type="archimate:ApplicationComponent" name="Facility Registry" id="id-fr">
      <property key="fhir-actor" value="FacilityRegistry"/>
    </element>
    <element xsi:type="archimate:ApplicationComponent" name="Untagged" id="id-u"/>
    <element xsi:type="archimate:DataObject" name="Record" id="id-d">
      <property key="fhir-actor" value="Record"/>
    </element>
    <element xsi:type="archimate:ApplicationComponent" name="Copy" id="id-copy">
      <property key="fhir-actor" value="ClientRegistry"/>
    </element>
  </folder>
  <folder name="Business" id="id-f2" type="business">
    <element xsi:type="archimate:BusinessRole" name="Health worker" id="id-hw">
      <property key="fhir-actor" value="health worker"/>
    </element>
  </folder>
</archimate:model>`;

describe("actors generated from the model", () => {
  const model = parseArchimate(XML);
  const { actors, problems } = actorsOf(model);

  it("takes only tagged elements, and says what is wrong with a tag", () => {
    expect(actors.map((a) => [a.id, a.element.id, a.type])).toEqual([
      ["ClientRegistry", "id-cr", "system"],
      ["FacilityRegistry", "id-fr", "system"],
    ]);
    expect(problems).toEqual([
      `id-d "Record": a DataObject cannot be an actor (an application or technology element, or a business actor or role)`,
      `id-copy "Copy": fhir-actor="ClientRegistry" is already on id-cr`,
      `id-hw "Health worker": fhir-actor="health worker" is not an FSH instance id (a letter, then letters, digits, . or -)`,
    ]);
    expect(actorTypeOf("BusinessRole")).toBe("person");
    expect(actorTypeOf("Goal")).toBeUndefined();
  });

  it("writes FSH from the element: name, description, type and a reference back", () => {
    const fsh = actorsFsh(actors, { model: "1.0.0", iri: (id) => `https://example.org/archimate/1.0.0/elements/${id}.jsonld` });
    expect(fsh.startsWith("// GENERATED by archimate-actors from ArchiMate model 1.0.0")).toBe(true);
    expect(fsh).toContain(`Instance: ClientRegistry\nInstanceOf: ActorDefinition\nUsage: #definition\n* name = "Client Registry"`);
    expect(fsh).toContain(`* description = "Keeps one record per person, \\"uniquely\\"."`);
    expect(fsh).toContain(`* type = #system\n* reference[0] = "https://example.org/archimate/1.0.0/elements/id-cr.jsonld"`);
    // No documentation, no description line: nothing is invented.
    expect(fsh.split("Instance: FacilityRegistry")[1]).not.toContain("description");
  });

  it("names the hand-written actors no tagged element generates yet", () => {
    const hand = `Instance: ClientRegistry\nInstanceOf: ActorDefinition\n* name = "x"\n\nInstance: SharedHealthRecord\nInstanceOf: ActorDefinition\n\nInstance: Other\nInstanceOf: Patient\n`;
    expect(handWrittenActors(hand)).toEqual(["ClientRegistry", "SharedHealthRecord"]);
  });
});
